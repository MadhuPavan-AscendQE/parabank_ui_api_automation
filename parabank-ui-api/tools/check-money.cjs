const {execFileSync}=require('node:child_process');
const path=require('node:path');const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
execFileSync(process.execPath,[require.resolve('typescript/bin/tsc'),'--outDir','.domain-check','--target','ES2022','--module','commonjs','--skipLibCheck','src/domain/money/cents.ts','src/domain/ledger/account.ts','src/data/customer.factory.ts','src/api/contracts/validate.ts'],{cwd:root,stdio:'inherit'});
const {cents,parseMoney,amountInput}=require(path.join(root,'.domain-check/domain/money/cents.js'));
const {customerData}=require(path.join(root,'.domain-check/data/customer.factory.js'));
let count=0;const check=(fn)=>{fn();count++;};
check(()=>assert.equal(parseMoney('$1,234.56'),123456));
check(()=>assert.equal(parseMoney('-$0.01'),-1));
check(()=>assert.equal(parseMoney('$0.00'),0));
check(()=>assert.equal(amountInput(cents(1)),'0.01'));
check(()=>assert.equal(amountInput(cents(-1234)),'-12.34'));
for(const invalid of ['$1,23.45','$12.345','$NaN','1e3','$12','($1.00)'])check(()=>assert.throws(()=>parseMoney(invalid)));
check(()=>assert.throws(()=>cents(1.5)));
check(()=>assert.throws(()=>parseMoney('$9007199254740992.00')));
check(()=>{const c=customerData();assert.ok(c.username.length<=20&&c.password.length<=20);assert.notEqual(c.username,customerData().username);});
const {apiCents}=require(path.join(root,'.domain-check/api/contracts/validate.js'));
check(()=>assert.equal(apiCents(1.23),123));
check(()=>assert.equal(apiCents(0.1),10));
check(()=>assert.throws(()=>apiCents(1.234)));
check(()=>assert.throws(()=>apiCents(Infinity)));
check(()=>assert.throws(()=>apiCents(9007199254740992)));
console.log(`${count} domain/data checks passed; no browser or server actions.`);
